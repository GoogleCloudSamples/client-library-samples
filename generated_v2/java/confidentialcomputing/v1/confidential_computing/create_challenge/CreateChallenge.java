package com.google.cloud.confidentialcomputing.v1;

// [START confidentialcomputing_v1_confidentialcomputing_challenge_create]
import com.google.cloud.confidentialcomputing.v1.Challenge;
import com.google.cloud.confidentialcomputing.v1.ConfidentialComputingClient;
import java.io.IOException;

public class CreateChallenge {

  public static void main(String[] args) throws Exception {
    String projectId = "example-project_id";
    String locationId = "example-location_id";
    createChallenge(projectId, locationId);
  }

  public static void createChallenge(String projectId, String locationId) throws Exception {
    // Initialize client that will be automatically closed at the end of the try block.
    try (ConfidentialComputingClient client = ConfidentialComputingClient.create()) {
      // Challenge fields are output-only and generated by the server.
      Challenge challenge = Challenge.newBuilder().build();
      String parent = String.format("projects/%s/locations/%s", projectId, locationId);

      Challenge response = client.createChallenge(parent, challenge);
      System.out.println("Created challenge: " + response.getName());
    }
  }
}
// [END confidentialcomputing_v1_confidentialcomputing_challenge_create]
