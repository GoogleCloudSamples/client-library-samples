'use strict';

const {BigtableTableAdminClient} = require('@google-cloud/bigtable').v2;
const {status} = require('@grpc/grpc-js');

const client = new BigtableTableAdminClient();

/**
 * Checks whether replication has caught up for a Bigtable table.
 *
 * @param {string} projectId - The Google Cloud project ID (for example, 'example-project-id').
 * @param {string} instanceId - The ID of the Bigtable instance containing the table (for example, 'example-instance-id').
 * @param {string} tableId - The ID of the Bigtable table to check replication consistency for (for example, 'example-table-id').
 * @param {string} consistencyToken - The replication consistency token generated by calling GenerateConsistencyToken for the table (for example, 'example-token').
 */
async function checkConsistency(projectId, instanceId, tableId, consistencyToken) {
  try {
    const name = `projects/${projectId}/instances/${instanceId}/tables/${tableId}`;
    const request = {
      name,
      consistencyToken,
    };

    const [response] = await client.checkConsistency(request);
    console.log(`Replication consistency status: ${response.consistent}`);
  } catch (err) {
    if (err.code === status.NOT_FOUND) {
      console.error(`Resource not found: ${err.message}`);
    } else if (err.code === status.INVALID_ARGUMENT) {
      console.error(`Invalid argument: ${err.message}`);
    } else {
      console.error(`API error (${err.code}): ${err.message}`);
    }
  }
}

module.exports = { checkConsistency };
// [END bigtable_v2_bigtabletableadmin_check_consistency]
