package com.google.cloud.migrationcenter.v1;

// [START migrationcenter_v1_migrationcenter_report_create]
import com.google.cloud.migrationcenter.v1.MigrationCenterClient;
import com.google.cloud.migrationcenter.v1.Report;
import com.google.cloud.migrationcenter.v1.ReportConfigName;
import java.io.IOException;
import java.util.concurrent.ExecutionException;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.TimeoutException;

public class CreateReport {

  public static void main(String[] args) throws Exception {
    String reportId = "example-report_id";
    String projectId = "example-project_id";
    String locationId = "example-location_id";
    String reportConfigId = "example-report_config_id";
    createReport(reportId, projectId, locationId, reportConfigId);
  }

  public static void createReport(
      String reportId, String projectId, String locationId, String reportConfigId)
      throws Exception {
    try (MigrationCenterClient client = MigrationCenterClient.create()) {
      String parent = ReportConfigName.of(projectId, locationId, reportConfigId).toString();
      Report report =
          Report.newBuilder()
              .setType(Report.Type.TOTAL_COST_OF_OWNERSHIP)
              .setDisplayName("Total Cost of Ownership Report")
              .setDescription("Total cost of ownership report generated by Migration Center")
              .build();

      // Initialize the long-running operation and wait for completion
      Report response = client.createReportAsync(parent, report, reportId).get();
      System.out.println("Created report: " + response.getName());
      System.out.println("Report state: " + response.getState());
    }
  }
}
// [END migrationcenter_v1_migrationcenter_report_create]
