package com.google.cloud.publicca.v1beta1;

// [START publicca_v1beta1_publiccertificateauthorityservice_externalaccountkey_create]
import com.google.cloud.security.publicca.v1beta1.ExternalAccountKey;
import com.google.cloud.security.publicca.v1beta1.PublicCertificateAuthorityServiceClient;

public class CreateExternalAccountKey {

  public static void main(String[] args) throws Exception {
    String projectId = "example-project-id";
    // Public Certificate Authority currently supports only the global location.
    String locationId = "global";
    createExternalAccountKey(projectId, locationId);
  }

  public static void createExternalAccountKey(String projectId, String locationId)
      throws Exception {
    try (PublicCertificateAuthorityServiceClient client =
        PublicCertificateAuthorityServiceClient.create()) {
      String parent = String.format("projects/%s/locations/%s", projectId, locationId);
      // All ExternalAccountKey fields are generated by the server upon creation.
      ExternalAccountKey externalAccountKey = ExternalAccountKey.newBuilder().build();

      ExternalAccountKey response = client.createExternalAccountKey(parent, externalAccountKey);
      System.out.println("Created external account key: " + response.getName());
      System.out.println("Key ID: " + response.getKeyId());
    }
  }
}
// [END publicca_v1beta1_publiccertificateauthorityservice_externalaccountkey_create]
